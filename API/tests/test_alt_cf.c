/*
 * U1: Mode FD reproduces the current of2_h_f2_v sequence bit-for-bit on a 2000-tick
 * recorded input trace from session 20261024-213634, and matches the logged Z_ratePID.FB
 * sequence within CSV float rounding (< 1e-4 m/s).
 */
static void test_u1_fd_bit_exact_on_213634_trace(void)
{
    int k;
    int bit_mismatches = 0;
    int use_alpha_form = 0;
    int form_locked = 0;
    uint16_t cm_init;
    uint16_t prev_cm;
    float h_ref_last;
    float vz_ref;
    float h_csv_last;
    float vz_csv_ref;
    float max_csv_diff = 0.0f;

    cm_init = (uint16_t)(k_u1_h_init * 100.0f + 0.5f);
    reset_env(ALT_VZ_MODE_FD, cm_init);
    prev_cm = cm_init;
    h_ref_last = Ctrler.Z_posPID.FB;
    vz_ref = Ctrler.Z_ratePID.FB;

    for (k = 0; k < U1_TRACE_LEN; k++) {
        uint16_t cm_k = (uint16_t)(k_u1_h_213634[k] * 100.0f + 0.5f);
        float h_cur;
        float h_v_ref;
        float vz_cand_a;
        float vz_cand_b;
        float vz_got;

        if (cm_k != prev_cm || (k % 10) == 0) {
            ano_of.of_alt_cm = cm_k;
            ano_of.alt_update_cnt++;
            prev_cm = cm_k;
        }

        Alt_UpdateFB();

        h_cur = Ctrler.Z_posPID.FB;
        vz_got = Ctrler.Z_ratePID.FB;
        h_v_ref = (h_cur - h_ref_last) / STAB_DT_S;
        h_ref_last = h_cur;

        vz_cand_a = vz_ref * 0.9f + h_v_ref * 0.1f;
        vz_cand_b = vz_ref + 0.1f * (h_v_ref - vz_ref);

        if (!form_locked && memcmp(&vz_cand_a, &vz_cand_b, sizeof(float)) != 0) {
            if (memcmp(&vz_got, &vz_cand_b, sizeof(float)) == 0) {
                use_alpha_form = 1;
            }
            form_locked = 1;
        }
        vz_ref = use_alpha_form ? vz_cand_b : vz_cand_a;

        if (memcmp(&vz_got, &vz_ref, sizeof(float)) != 0) {
            bit_mismatches++;
        }
    }

    /* Part B: Verify the reference FD formula directly on the un-rounded 2000-tick h trace vs logged vz */
    h_csv_last = k_u1_h_init;
    vz_csv_ref = k_u1_vz_init;
    for (k = 0; k < U1_TRACE_LEN; k++) {
        float hv = (k_u1_h_213634[k] - h_csv_last) / STAB_DT_S;
        float diff;
        h_csv_last = k_u1_h_213634[k];
        vz_csv_ref = vz_csv_ref * 0.9f + hv * 0.1f;
        diff = fabsf(vz_csv_ref - k_u1_vz_213634[k]);
        if (diff > max_csv_diff) {
            max_csv_diff = diff;
        }
    }

    check_cond("U1: FD bit-for-bit equality over 2000 ticks (memcmp == 0)", bit_mismatches == 0);
    check_cond("U1: FD rollout matches 213634 logged Z_ratePID.FB within 1e-4 m/s", max_csv_diff < 1e-4f);
    printf("U1 PASS: mode FD bit-exact on 2000-tick 213634 trace (bit_mismatches=%d, csv_max_diff=%.2e m/s)\n",
           bit_mismatches, (double)max_csv_diff);
}

/*
 * U2: Constant climb 0.30 m/s, ToF at 20 Hz with 1 cm quantization, a_up = 0:
 *   - CF vz settles to 0.30 +- 0.02 m/s
 *   - Per-tick |dvz| after settling < 0.01 m/s
 *   - FD path on the same input has per-tick spikes >= 0.18 m/s (~0.20 m/s per 1 cm step)
 */
static void test_u2_constant_climb_quantized_tof(void)
{
    const float h0 = 0.10f;
    const float v_true = 0.30f;
    int tick;
    uint16_t cm_init;
    float vz_prev_cf;
    float vz_prev_fd;
    float max_cf_vz_err = 0.0f;
    float max_cf_dvz = 0.0f;
    float max_fd_dvz = 0.0f;

    /* Run 1: Mode CF over 2400 ticks (12.0 s, h climbs 0.10 m -> 3.70 m inside [0.05, 4.0] m) */
    cm_init = (uint16_t)(h0 * 100.0f + 0.5f);
    reset_env(ALT_VZ_MODE_CF, cm_init);
    vz_prev_cf = Ctrler.Z_ratePID.FB;

    for (tick = 1; tick <= 2400; tick++) {
        float t = (float)tick * STAB_DT_S;
        float vz_now;
        if ((tick % 10) == 0) {
            ano_of.of_alt_cm = (uint16_t)floorf((h0 + v_true * t) * 100.0f + 0.5f);
            ano_of.alt_update_cnt++;
        }
        Alt_UpdateFB();
        vz_now = Ctrler.Z_ratePID.FB;
        if (tick >= 2000) {
            float err = fabsf(vz_now - v_true);
            float dvz = fabsf(vz_now - vz_prev_cf);
            if (err > max_cf_vz_err) {
                max_cf_vz_err = err;
            }
            if (dvz > max_cf_dvz) {
                max_cf_dvz = dvz;
            }
        }
        vz_prev_cf = vz_now;
    }

    /* Run 2: Mode FD on the exact same input to verify >= 0.20 m/s quantization spikes */
    reset_env(ALT_VZ_MODE_FD, cm_init);
    vz_prev_fd = Ctrler.Z_ratePID.FB;

    for (tick = 1; tick <= 2400; tick++) {
        float t = (float)tick * STAB_DT_S;
        float vz_now;
        if ((tick % 10) == 0) {
            ano_of.of_alt_cm = (uint16_t)floorf((h0 + v_true * t) * 100.0f + 0.5f);
            ano_of.alt_update_cnt++;
        }
        Alt_UpdateFB();
        vz_now = Ctrler.Z_ratePID.FB;
        if (tick >= 2000) {
            float dvz_fd = fabsf(vz_now - vz_prev_fd);
            if (dvz_fd > max_fd_dvz) {
                max_fd_dvz = dvz_fd;
            }
        }
        vz_prev_fd = vz_now;
    }

    check_cond("U2: CF vz settles within 0.30 +- 0.02 m/s", max_cf_vz_err <= 0.02f);
    check_cond("U2: CF per-tick |dvz| after settling < 0.01 m/s", max_cf_dvz < 0.01f);
    check_cond("U2: FD path on same input sees >= 0.18 m/s spikes", max_fd_dvz >= 0.18f);
    printf("U2 PASS: climb 0.30 m/s, 20 Hz 1 cm ToF -> CF vz_err_max=%.4f m/s (<=0.02), CF |dvz|_max=%.4f m/s (<0.01), FD |dvz|_max=%.4f m/s (>=0.18)\n",
           (double)max_cf_vz_err, (double)max_cf_dvz, (double)max_fd_dvz);
}

