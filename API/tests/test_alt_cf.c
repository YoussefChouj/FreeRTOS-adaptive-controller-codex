static int g_fail_count = 0;
static int g_pass_count = 0;

static void check_cond(const char *name, int cond)
{
    if (cond) {
        g_pass_count++;
    } else {
        g_fail_count++;
        printf("FAIL: %s\n", name);
    }
}

static void reset_env(uint8_t mode, uint16_t init_cm)
{
    int i;
    float h_init = (float)init_cm * M_PER_CM;
    memset(&ano_of, 0, sizeof(ano_of));
    memset(&IMU_Data, 0, sizeof(IMU_Data));
    memset(&imu_data, 0, sizeof(imu_data));
    memset(&Ctrler, 0, sizeof(Ctrler));
    Cos_roll_01 = 1.0f;
    Cos_pitch_01 = 1.0f;
    Lin_Acc_X_body = 0.0f;
    Lin_Acc_Y_body = 0.0f;
    Lin_Acc_Z_body = 0.0f;
    Gravity_Body_X = 0.0f;
    Gravity_Body_Y = 0.0f;
    Gravity_Body_Z = 1.0f;
    Flight_Control_Lock = 0U;
    Alt_TestResetAll();
    ano_of.of_alt_cm = init_cm;
    ano_of.of2_raw_h = h_init;
    ano_of.of2_h = h_init;
    ano_of.of2_last_h = h_init;
    g_alt_vz_mode = mode;
    for (i = 0; i < 3; i++) {
        ano_of.alt_update_cnt++;
        Alt_UpdateFB();
    }
    Alt_CfReset(h_init, 1U);
    Flight_Control_Lock = 1U;
    s_alt_armed_prev = 1U;  /* start airborne: no arm-edge reset on the first tick */
}

