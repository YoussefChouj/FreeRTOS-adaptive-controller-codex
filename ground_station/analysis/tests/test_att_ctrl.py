import numpy as np
from scipy.linalg import solve_discrete_are
from ground_station.analysis.att_ctrl import aug_ad, lqr_gain, fw_header, MODELS

def test_lqr_matches_scipy():
    m = MODELS["roll"]
    q = (1.0, 1.0, 1.0, 1.0)
    r = 1.0
    a, b = aug_ad(m)
    b = b.reshape(4, 1)
    p = solve_discrete_are(a, b, np.diag(q), np.array([[r]]))
    expected_k = np.linalg.solve(r + b.T @ p @ b, b.T @ p @ a).ravel()

    k = lqr_gain(m, q, r)
    np.testing.assert_allclose(k, expected_k, rtol=1e-5)

def test_fw_header():
    header = fw_header()
    assert "GENERATED by" in header
    assert "ATTC_ROLL_PHI" in header
    assert "ATTC_Z_MPC_H" in header
