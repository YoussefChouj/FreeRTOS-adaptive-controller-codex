"""Cross-day flight history: one row per logs/flights/<day>/<nn_name>/ folder.

    python -m ground_station.lab.flight_index            # writes logs/flights/INDEX.md and logs/flights/index.csv
    python -m ground_station.lab.flight_index --grep lqr # print only the rows whose name or controller match

Reads only what fly already files per flight (debrief.txt, metadata.json, gains.json, scorecard.json, the .fly
copy). A missing file leaves its columns empty: older folders predate some of them. status is debrief line 1, except
"aborted L<n>" when line 2 says the safety monitor landed it (note = why).
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FLIGHTS = ROOT / "logs" / "flights"
COLUMNS = ("day", "folder", "fly", "status", "air_s", "hover_rms_cm", "traj_rms_cm", "controller", "preset",
           "git", "verdict", "note")
_RMS = re.compile(r"rms (\d+)/(\d+)/(\d+)")


def _json(p: Path) -> dict:
    try:
        d = json.loads(p.read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else {}
    except (OSError, ValueError):
        return {}


def _rms(line: str) -> str:
    m = _RMS.search(line)
    return "/".join(m.groups()) if m else ""


def row(folder: Path) -> dict:
    """One flight folder -> {COLUMNS}; strings, empty when the folder does not record it."""
    r = dict.fromkeys(COLUMNS, "")
    r["day"], r["folder"] = folder.parent.name, folder.name
    fly = sorted(folder.glob("*.fly"))
    r["fly"] = fly[0].stem if fly else ""
    try:
        lines = (folder / "debrief.txt").read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        lines = []
    if lines:
        head = lines[0].split()
        r["status"] = head[0] if head else ""
        if "air" in head and head.index("air") + 1 < len(head):
            r["air_s"] = head[head.index("air") + 1]
    for ln in lines[1:6]:
        if ln.startswith("ABORTED") and not r["note"]:
            # line 1 says "complete" for a flight the safety monitor landed (85 of 196 folders on 10-28): line 2 wins
            r["status"] = "aborted " + ln.split()[1] if len(ln.split()) > 1 else "aborted"
            r["note"] = ln.split(": ", 1)[-1].split(" (the safety monitor")[0][:90]
        elif ln.startswith("HOVER") and not r["hover_rms_cm"]:
            r["hover_rms_cm"] = _rms(ln)
        elif ln.startswith("TRAJ") and not r["traj_rms_cm"]:
            r["traj_rms_cm"] = _rms(ln)
    meta = _json(folder / "metadata.json")
    r["controller"] = str(meta.get("controller") or "")
    r["preset"] = str(meta.get("preset") or _json(folder / "gains.json").get("base") or "")
    r["git"] = str(meta.get("git_commit") or "")[:8]
    card = _json(folder / "scorecard.json")
    v = card.get("verdict") or card.get("overall") or card.get("status")
    r["verdict"] = str(v or "")
    return r


def rows(root: Path = FLIGHTS) -> list[dict]:
    return [row(f) for day in sorted(p for p in root.iterdir() if p.is_dir())
            for f in sorted(p for p in day.iterdir() if p.is_dir())] if root.is_dir() else []


def markdown(rs: list[dict]) -> str:
    out = ["# Flight history (generated by `python -m ground_station.lab.flight_index`; do not edit)", "",
           f"{len(rs)} flights. rms = x/y/z error in cm (debrief.txt). Empty cell = not recorded by that day's fly.", ""]
    for day in sorted({r["day"] for r in rs}):
        day_rows = [r for r in rs if r["day"] == day]
        out += [f"## {day} ({len(day_rows)})", "", "| " + " | ".join(COLUMNS[1:]) + " |",
                "|" + "---|" * (len(COLUMNS) - 1)]
        out += ["| " + " | ".join(r[c].replace("|", "/") for c in COLUMNS[1:]) + " |" for r in day_rows]
        out.append("")
    return "\n".join(out)


def write(root: Path = FLIGHTS) -> list[dict]:
    """Rebuild root/INDEX.md and root/index.csv; prints nothing (labday calls it from its scoring thread)."""
    rs = rows(root)
    (root / "INDEX.md").write_text(markdown(rs), encoding="utf-8")
    with (root / "index.csv").open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, COLUMNS)
        w.writeheader()
        w.writerows(rs)
    return rs


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=FLIGHTS)
    ap.add_argument("--grep", help="print matching rows only (name, .fly or controller), write nothing")
    a = ap.parse_args(argv)
    if a.grep:
        pat = re.compile(a.grep, re.I)
        for r in rows(a.root):
            if pat.search(" ".join((r["folder"], r["fly"], r["controller"]))):
                print("  ".join(f"{r[c]}" for c in COLUMNS if r[c]))
        return 0
    rs = write(a.root)
    print(f"{len(rs)} flights -> {a.root / 'INDEX.md'} and index.csv")
    return 0


if __name__ == "__main__":
    sys.exit(main())
