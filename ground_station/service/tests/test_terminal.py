# 1. Service builder passes a TerminalManager
# -----------------------------------------------------------------------


def test_service_builder_passes_terminal_manager():
    """ApiServer has a terminal_manager when constructed with one."""
    schema = StreamSchema(1, 1, 4,
                          (StreamRange(0x20000000, 4, 1, "altitude", "f"),), 0)
    service = GroundStationService(store=SessionStore(), schemas=[schema], source="sim")
    service.start()

    from ground_station.service.terminal import TerminalManager
    with tempfile.TemporaryDirectory() as td:
        tm = TerminalManager(state_dir=Path(td))
        api = ApiServer(service, host="127.0.0.1", port=0, terminal_manager=tm)
        api.start()
        try:
            assert api.terminal_manager is not None
            assert api.terminal_manager is tm
        finally:
            api.stop()
            service.stop()


