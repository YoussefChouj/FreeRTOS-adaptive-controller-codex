# -----------------------------------------------------------------------
# 3. Token is 32 hex chars and comes from `secrets`
# -----------------------------------------------------------------------


def test_token_is_32_hex_chars_from_secrets():
    """A freshly generated token is 32 hex characters from secrets.token_hex(16)."""
    from ground_station.service.terminal import _ensure_token
    with tempfile.TemporaryDirectory() as td:
        state_dir = Path(td)
        # Monkey-patch secrets.token_hex to return a known value
        with patch("ground_station.service.terminal.secrets.token_hex", return_value="a" * 32):
            token = _ensure_token(state_dir)
            assert len(token) == 32
            assert all(c in "0123456789abcdef" for c in token), "token must be hex"


def test_reloaded_token_matches_stored():
    """Reading back the token file returns the same value."""
    from ground_station.service.terminal import _ensure_token
    with tempfile.TemporaryDirectory() as td:
        state_dir = Path(td)
        with patch("ground_station.service.terminal.secrets.token_hex", return_value="deadbeef" * 4):
            t1 = _ensure_token(state_dir)
        t2 = _ensure_token(state_dir)
        assert t1 == t2


# -----------------------------------------------------------------------
# 4. GET /health includes process_rss_mb
# -----------------------------------------------------------------------


def test_health_has_process_rss_mb():
    """GET /health returns a process_rss_mb field (number or None)."""
    schema = StreamSchema(1, 1, 4,
                          (StreamRange(0x20000000, 4, 1, "altitude", "f"),), 0)
    service = GroundStationService(store=SessionStore(), schemas=[schema], source="sim")
    service.start()
    api = ApiServer(service, host="127.0.0.1", port=0)
    api.start()
    try:
        port = api.address[1]
        base = "http://127.0.0.1:%d" % port
        status, body = _get_json(base + "/health")
        assert status == 200
        assert "process_rss_mb" in body
        val = body["process_rss_mb"]
        # With psutil it is a float rounded to 1 decimal; without it is None.
        assert val is None or isinstance(val, (int, float)), f"got {val!r}"
    finally:
        api.stop()
        service.stop()
